/**
 * 子代理共用的「工作目录」文本块（用户 2026-09-16）：所有子代理的出生包与
 * 回合提示词统一写明**工作目录**（工程根：代码产出写这里）与**任务目录**
 * （留言板 / 纪要 / 计划 / 文档所在）的绝对路径——路径全由宿主算好下发，
 * 子代理照抄，不自己拼名字、不另建同名变体。
 *
 * 口径原先只存在于成员简报（prompts/spawn/member.ts），领队子代理与构建
 * 子代理的提示词里缺失，故抽到此处共用一个来源。纯文本函数：值由 runtime
 * 侧按任务现读（工作目录取任务自己的 task.work_dir，任务目录取
 * work_dir + task_dir），本模块不触盘。
 *
 * @module dsh-eteams/prompts/spawn/workDirs
 */

/** 工作目录块：`## 你的工作目录` + 工作目录行 +（给了任务目录时）任务目录行。 */
export function workDirsBlock(opts: {
  /** 工作目录绝对路径（= 工程根 / 本任务绑定的工作区，代码产出写这里）。 */
  workDir: string;
  /** 任务目录绝对路径（留言板 / 纪要 / 计划 / 文档都在这里）；缺省不渲染该行。 */
  taskDir?: string;
}): string {
  return [
    '## 你的工作目录',
    `- 代码产出写工程根（本任务绑定的工作区，**以这个路径为准**）：${opts.workDir}`,
    ...(opts.taskDir !== undefined
      ? [`- 任务目录（留言板 / 纪要 / 计划 / 文档 都在这里）：${opts.taskDir}`]
      : []),
  ].join('\n');
}
