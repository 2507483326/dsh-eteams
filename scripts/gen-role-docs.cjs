// One-shot generator: fetch the five agency-agents-zh role markdown files
// verbatim, strip YAML frontmatter, and emit
// src/host/prompts/personas/roleDocs.ts (JSON-escaped string literals —
// no manual escaping).
const fs = require('fs');
const path = require('path');
const os = require('os');

const BASE = 'https://raw.githubusercontent.com/holden-cpu/agency-agents-zh/main';
const ROLES = [
  ['前端开发者', 'engineering/engineering-frontend-developer.md', 'agz-eng-frontend.md'],
  ['后端架构师', 'engineering/engineering-backend-architect.md', 'agz-eng-backend.md'],
  ['UI 设计师', 'design/design-ui-designer.md', 'agz-design-ui.md'],
  ['趣味注入师', 'design/design-whimsy-injector.md', 'agz-design-whimsy.md'],
  ['项目牧羊人', 'project-management/project-management-project-shepherd.md', 'agz-pm-shepherd.md'],
];

function stripFrontmatter(raw) {
  const text = raw.replace(/^﻿/, '');
  if (text.startsWith('---')) {
    const end = text.indexOf('\n---', 3);
    if (end >= 0) {
      return text
        .slice(text.indexOf('\n', end + 1) + 1)
        .replace(/^\s*\n/, '')
        .trimEnd();
    }
  }
  return text.trimEnd();
}

async function fetchRole([role, repoPath, cacheName]) {
  const cache = path.join(os.tmpdir(), cacheName);
  try {
    const res = await fetch(`${BASE}/${repoPath}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const raw = await res.text();
    fs.writeFileSync(cache, raw, 'utf8');
    console.log(`${role}: fetched ${repoPath} (${raw.length} bytes)`);
    return [role, stripFrontmatter(raw)];
  } catch (e) {
    if (fs.existsSync(cache)) {
      const raw = fs.readFileSync(cache, 'utf8');
      console.log(`${role}: network failed (${e.message}), using cache`);
      return [role, stripFrontmatter(raw)];
    }
    throw e;
  }
}

(async () => {
  const entries = [];
  for (const spec of ROLES) entries.push(await fetchRole(spec));
  const lines = [
    '/**',
    ' * Role playbooks imported VERBATIM from holden-cpu/agency-agents-zh (MIT).',
    ' * Generated by scripts tooling — frontmatter stripped, bodies untouched.',
    ' * Source: https://github.com/holden-cpu/agency-agents-zh',
    ' *',
    ' * @module dsh-eteams/prompts/personas/roleDocs',
    ' */',
    'export const ROLE_DOCS: Record<string, string> = {',
    ...entries.map(([role, md]) => `  '${role}': ${JSON.stringify(md)},`),
    '};',
    '',
  ];
  // 输出路径按本脚本位置推导（仓库根/scripts → src/host/prompts/personas），
  // 不再硬编码绝对路径。
  const outPath = path.join(__dirname, '..', 'src', 'host', 'prompts', 'personas', 'roleDocs.ts');
  fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
  for (const [role, md] of entries) console.log(`${role}: ${md.split('\n').length} lines embedded`);
})();
